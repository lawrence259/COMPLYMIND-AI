-- 1. Discrepancy Findings (Evidence Extraction & Verification)
CREATE TABLE IF NOT EXISTS discrepancy_findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    evidence_document_id BIGINT,
    application_requirement_id BIGINT NOT NULL,
    finding_type VARCHAR(64) NOT NULL,
    field_name VARCHAR(100) NOT NULL,
    declared_value VARCHAR(255),
    extracted_value VARCHAR(255),
    source_citation VARCHAR(255),
    source_page INT,
    confidence_score NUMERIC(5,2),
    regulatory_reference VARCHAR(255),
    severity VARCHAR(32) NOT NULL,
    review_status VARCHAR(32) NOT NULL DEFAULT 'PENDING_REVIEW',
    reviewer_notes TEXT,
    reviewed_by_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_discrepancy_app FOREIGN KEY (application_id) REFERENCES compliance_applications(id) ON DELETE CASCADE,
    CONSTRAINT fk_discrepancy_evidence FOREIGN KEY (evidence_document_id) REFERENCES evidence_documents(id) ON DELETE SET NULL,
    CONSTRAINT fk_discrepancy_app_req FOREIGN KEY (application_requirement_id) REFERENCES application_requirements(id) ON DELETE CASCADE,
    CONSTRAINT fk_discrepancy_user FOREIGN KEY (reviewed_by_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_discrepancy_app ON discrepancy_findings(application_id);
CREATE INDEX IF NOT EXISTS idx_discrepancy_req ON discrepancy_findings(application_requirement_id);
CREATE INDEX IF NOT EXISTS idx_discrepancy_status ON discrepancy_findings(review_status);
