-- ====================================================================
-- COMPLYMIND AI Schema Migration V1
-- Supports PostgreSQL 14+ and H2 (PostgreSQL compatibility mode)
-- ====================================================================

-- 1. Institutions
CREATE TABLE institutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(64) NOT NULL,
    aicte_permanent_id VARCHAR(100),
    state VARCHAR(100),
    city VARCHAR(100),
    address VARCHAR(500),
    contact_email VARCHAR(150),
    contact_phone VARCHAR(50),
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

-- 2. Users
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(50) NOT NULL,
    institution_id BIGINT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_users_institution FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE SET NULL
);

-- 3. Compliance Frameworks
CREATE TABLE compliance_frameworks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    cycle_year VARCHAR(32) NOT NULL,
    description TEXT,
    source_url VARCHAR(500),
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

-- 4. Compliance Rules
CREATE TABLE compliance_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    framework_id BIGINT NOT NULL,
    rule_code VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    source_section VARCHAR(100),
    source_url VARCHAR(500),
    applicability VARCHAR(255),
    required_evidence_type VARCHAR(100),
    validation_method VARCHAR(100),
    version VARCHAR(32) NOT NULL DEFAULT '1.0',
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    reviewer_notes TEXT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_rules_framework FOREIGN KEY (framework_id) REFERENCES compliance_frameworks(id) ON DELETE CASCADE,
    CONSTRAINT uk_framework_rule UNIQUE (framework_id, rule_code, version)
);

-- 5. Requirements (Master catalog under framework)
CREATE TABLE requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    framework_id BIGINT NOT NULL,
    code VARCHAR(64) NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    category VARCHAR(100) NOT NULL,
    is_mandatory BOOLEAN NOT NULL DEFAULT TRUE,
    default_deadline_days INT NOT NULL DEFAULT 30,
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_requirements_framework FOREIGN KEY (framework_id) REFERENCES compliance_frameworks(id) ON DELETE CASCADE,
    CONSTRAINT uk_framework_req_code UNIQUE (framework_id, code)
);

-- 6. Requirement Dependencies (Master DAG edges)
CREATE TABLE requirement_dependencies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_requirement_id BIGINT NOT NULL,
    dependent_requirement_id BIGINT NOT NULL,
    dependency_type VARCHAR(50) NOT NULL DEFAULT 'HARD_BLOCKER',
    description VARCHAR(255),
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_dep_source FOREIGN KEY (source_requirement_id) REFERENCES requirements(id) ON DELETE CASCADE,
    CONSTRAINT fk_dep_target FOREIGN KEY (dependent_requirement_id) REFERENCES requirements(id) ON DELETE CASCADE,
    CONSTRAINT uk_source_target UNIQUE (source_requirement_id, dependent_requirement_id)
);

-- 7. Compliance Applications
CREATE TABLE compliance_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_number VARCHAR(100) NOT NULL UNIQUE,
    institution_id BIGINT NOT NULL,
    framework_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    academic_year VARCHAR(32) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    submitted_at TIMESTAMP,
    risk_score DECIMAL(5,2) DEFAULT 0.0,
    risk_band VARCHAR(32) DEFAULT 'LOW',
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_by_user_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_app_institution FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE RESTRICT,
    CONSTRAINT fk_app_framework FOREIGN KEY (framework_id) REFERENCES compliance_frameworks(id) ON DELETE RESTRICT,
    CONSTRAINT fk_app_created_by FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- 8. Application Requirements (Instance of a requirement for an application)
CREATE TABLE application_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    requirement_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    deadline TIMESTAMP,
    compliance_notes TEXT,
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_app_req_app FOREIGN KEY (application_id) REFERENCES compliance_applications(id) ON DELETE CASCADE,
    CONSTRAINT fk_app_req_req FOREIGN KEY (requirement_id) REFERENCES requirements(id) ON DELETE RESTRICT,
    CONSTRAINT uk_app_requirement UNIQUE (application_id, requirement_id)
);

-- 9. Evidence Documents
CREATE TABLE evidence_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    application_requirement_id BIGINT,
    original_filename VARCHAR(255) NOT NULL,
    stored_filename VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    sha256_checksum VARCHAR(100) NOT NULL,
    version_number INT NOT NULL DEFAULT 1,
    review_status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    extracted_text TEXT,
    extraction_status VARCHAR(50) NOT NULL DEFAULT 'NOT_ATTEMPTED',
    extraction_error TEXT,
    uploaded_by_user_id BIGINT,
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_evidence_app FOREIGN KEY (application_id) REFERENCES compliance_applications(id) ON DELETE CASCADE,
    CONSTRAINT fk_evidence_app_req FOREIGN KEY (application_requirement_id) REFERENCES application_requirements(id) ON DELETE SET NULL,
    CONSTRAINT fk_evidence_user FOREIGN KEY (uploaded_by_user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- 10. Review Decisions
CREATE TABLE review_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_document_id BIGINT NOT NULL,
    application_requirement_id BIGINT NOT NULL,
    reviewer_user_id BIGINT NOT NULL,
    decision VARCHAR(50) NOT NULL,
    comments TEXT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_decision_evidence FOREIGN KEY (evidence_document_id) REFERENCES evidence_documents(id) ON DELETE CASCADE,
    CONSTRAINT fk_decision_app_req FOREIGN KEY (application_requirement_id) REFERENCES application_requirements(id) ON DELETE CASCADE,
    CONSTRAINT fk_decision_reviewer FOREIGN KEY (reviewer_user_id) REFERENCES users(id) ON DELETE RESTRICT
);

-- 11. Risk Assessments
CREATE TABLE risk_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    overall_score DECIMAL(5,2) NOT NULL,
    risk_band VARCHAR(32) NOT NULL,
    deadline_urgency_score DECIMAL(5,2) NOT NULL,
    blocked_dependency_score DECIMAL(5,2) NOT NULL,
    evidence_deficiency_score DECIMAL(5,2) NOT NULL,
    unresolved_pendency_score DECIMAL(5,2) NOT NULL,
    explanation_json TEXT,
    calculated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_risk_app FOREIGN KEY (application_id) REFERENCES compliance_applications(id) ON DELETE CASCADE
);

-- 12. Corrective Actions (Auto-Recovery Tasks)
CREATE TABLE corrective_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    application_requirement_id BIGINT,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    root_issue VARCHAR(255) NOT NULL,
    assigned_to_user_id BIGINT,
    due_date TIMESTAMP NOT NULL,
    priority VARCHAR(32) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(50) NOT NULL DEFAULT 'OPEN',
    resolution_summary TEXT,
    verified_by_user_id BIGINT,
    verified_at TIMESTAMP,
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_action_app FOREIGN KEY (application_id) REFERENCES compliance_applications(id) ON DELETE CASCADE,
    CONSTRAINT fk_action_app_req FOREIGN KEY (application_requirement_id) REFERENCES application_requirements(id) ON DELETE SET NULL,
    CONSTRAINT fk_action_assigned FOREIGN KEY (assigned_to_user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_action_verifier FOREIGN KEY (verified_by_user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- 13. Notifications
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    institution_id BIGINT,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    type VARCHAR(50) NOT NULL DEFAULT 'ALERT',
    link_url VARCHAR(255),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_notify_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_notify_inst FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE CASCADE
);

-- 14. Audit Events
CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_username VARCHAR(100) NOT NULL,
    actor_role VARCHAR(50) NOT NULL,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100) NOT NULL,
    entity_id VARCHAR(100),
    details TEXT,
    ip_address VARCHAR(100),
    created_at TIMESTAMP NOT NULL
);

-- Indexes for performance
CREATE INDEX idx_users_username ON users(username);
CREATE INDEX idx_users_institution ON users(institution_id);
CREATE INDEX idx_app_institution ON compliance_applications(institution_id);
CREATE INDEX idx_app_status ON compliance_applications(status);
CREATE INDEX idx_app_req_app ON application_requirements(application_id);
CREATE INDEX idx_evidence_app ON evidence_documents(application_id);
CREATE INDEX idx_dep_source ON requirement_dependencies(source_requirement_id);
CREATE INDEX idx_dep_target ON requirement_dependencies(dependent_requirement_id);
CREATE INDEX idx_risk_app ON risk_assessments(application_id);
CREATE INDEX idx_action_app ON corrective_actions(application_id);
CREATE INDEX idx_audit_created ON audit_events(created_at);
CREATE INDEX idx_notify_user ON notifications(user_id, is_read);
